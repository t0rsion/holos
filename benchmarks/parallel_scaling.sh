#!/usr/bin/env bash
# Parallel scaling of the holos reducer: one fixed cloud reduced at several
# thread counts. Reports wall time and speedup against threads=1. Asserts the
# diagram is identical across thread counts, as run.sh does. A timing whose
# diagram differs from the serial one is void.
#
# Results: benchmarks/results_parallel.txt (log) and .md (table). Both are
# gitignored. Every number must be reproducible by rerunning this script.
#
# CARGO may carry a toolchain: CARGO="cargo +1.92" ./parallel_scaling.sh
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: parallel_scaling.sh [-h]

Reduce one seeded point cloud at threads {1,2,4,8,16}, report wall time and
speedup vs threads=1, and assert the diagram is identical at every thread
count. No external tools required.

Environment:
  CARGO        cargo invocation (may carry a toolchain), default "cargo"
  N            cloud size (points), default 400
  COORD_DIM    coordinate dimension, default 3
  SEED         cloud seed, default 42
  MAXDIM       max homology dimension, default 2
  THRESHOLD    filtration threshold, default 0.5 (empty = enclosing radius)
  THREADS      space-separated thread counts, default "1 2 4 8 16"
  ALLOW_DIRTY  set to 1 to benchmark a dirty worktree (recorded as -DIRTY)
EOF
}

[[ "${1:-}" == "-h" || "${1:-}" == "--help" ]] && { usage; exit 0; }

source "$(dirname "$0")/_common.sh"
require_proc

N="${N:-400}"
COORD_DIM="${COORD_DIM:-3}"
SEED="${SEED:-42}"
MAXDIM="${MAXDIM:-2}"
THRESHOLD="${THRESHOLD-0.5}"
read -r -a THREAD_LIST <<<"${THREADS:-1 2 4 8 16}"

RESULTS="$HERE/results_parallel.txt"
RESULTS_MD="$HERE/results_parallel.md"

mkdir -p "$DATA"
build_holos
emit_provenance "$RESULTS" "holos parallel-scaling run"

cloud="$DATA/parallel_cloud_${N}.csv"
lower="$DATA/parallel_cloud_${N}.lower"
python3 "$HERE/gen_cloud.py" "$N" "$COORD_DIM" "$SEED" >"$cloud"
cloud_to_lower "$cloud" >"$lower"

holos_cmd_base=("$HOLOS_BIN" "$lower" --format lower-distance --dim "$MAXDIM")
[[ -n "$THRESHOLD" ]] && holos_cmd_base+=(--threshold "$THRESHOLD")

{
    echo "cloud: gen_cloud.py $N $COORD_DIM $SEED -> lower-distance"
    echo "maxdim: $MAXDIM  threshold: ${THRESHOLD:-enclosing radius}"
    echo "threads: ${THREAD_LIST[*]}"
    echo
} >>"$RESULTS"

{
    echo "<!-- Generated by benchmarks/parallel_scaling.sh. Do not edit; rerun the script. -->"
    echo
    echo "- N: $N  coord dim: $COORD_DIM  seed: $SEED  maxdim: $MAXDIM  threshold: ${THRESHOLD:-enclosing radius}"
    echo
    echo "| threads | wall (s) | speedup | peak RSS (MB) | diagram matches t=1 |"
    echo "|--:|--:|--:|--:|:--|"
} >>"$RESULTS_MD"

BASE_WALL=""
BASE_OUT=""
ANY_MISMATCH=0

for t in "${THREAD_LIST[@]}"; do
    out="$DATA/parallel_${N}_t${t}.out"
    stats="$(measure "$out" "${holos_cmd_base[@]}" --threads "$t")"
    wall="${stats#wall_s=}"
    wall="${wall%% *}"
    rss="${stats##*max_rss_kb=}"

    if [[ -z "$BASE_WALL" ]]; then
        BASE_WALL="$wall"
        BASE_OUT="$out"
        match="yes (baseline)"
    else
        match="$(compare_diagrams "$BASE_OUT" "$out")"
        [[ "$match" != yes ]] && ANY_MISMATCH=1
    fi
    sp="$(speedup "$BASE_WALL" "$wall")"

    {
        echo "== threads=$t"
        echo "cmd: ${holos_cmd_base[*]} --threads $t"
        echo "$stats  speedup=$sp  diagram_matches_t1=$match"
        echo
    } >>"$RESULTS"
    echo "| $t | $wall | $sp | $(kb_to_mb "$rss") | $match |" >>"$RESULTS_MD"
    echo "threads=$t wall=${wall}s speedup=$sp match=$match" >&2
done

echo "Results written to $RESULTS and $RESULTS_MD." >&2

if [[ "$ANY_MISMATCH" -ne 0 ]]; then
    echo "FAILURE: a thread count produced a different diagram than threads=1; timings void." >&2
    exit 1
fi
