#!/usr/bin/env bash
# Equal-core comparison against giotto-ph's parallel ripser. If
# `from gph import ripser_parallel` imports, run holos and giotto-ph on
# identical clouds at matched thread counts, then compare diagrams and wall
# time. If giotto-ph is absent, print a note and exit 0. This script never
# fails because the optional dependency is missing.
#
# giotto-ph: https://github.com/giotto-ai/giotto-ph  (pip install giotto-ph)
#
# Results: benchmarks/results_giotto.txt (log) and .md (table), gitignored.
#
# CARGO may carry a toolchain: CARGO="cargo +1.92" ./giotto_compare.sh
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: giotto_compare.sh [-h]

Compare holos against giotto-ph's ripser_parallel on identical seeded clouds
at matched thread counts (wall time + diagram agreement). Skips cleanly with
exit 0 if giotto-ph is not importable.

Environment:
  CARGO        cargo invocation (may carry a toolchain), default "cargo"
  N            cloud size (points), default 300
  COORD_DIM    coordinate dimension, default 3
  SEED         cloud seed, default 42
  MAXDIM       max homology dimension, default 2
  THRESHOLD    filtration threshold, default 0.6
  THREADS      space-separated thread counts, default "1 2 4 8"
  ALLOW_DIRTY  set to 1 to benchmark a dirty worktree (recorded as -DIRTY)
EOF
}

[[ "${1:-}" == "-h" || "${1:-}" == "--help" ]] && { usage; exit 0; }

source "$(dirname "$0")/_common.sh"

# The optional-dependency gate. It runs before any build or measurement, so
# the skip path is cheap and never fails.
if ! python3 -c 'from gph import ripser_parallel' 2>/dev/null; then
    echo "giotto-ph not installed, skipping"
    exit 0
fi

require_proc

N="${N:-300}"
COORD_DIM="${COORD_DIM:-3}"
SEED="${SEED:-42}"
MAXDIM="${MAXDIM:-2}"
THRESHOLD="${THRESHOLD:-0.6}"
read -r -a THREAD_LIST <<<"${THREADS:-1 2 4 8}"

RESULTS="$HERE/results_giotto.txt"
RESULTS_MD="$HERE/results_giotto.md"

mkdir -p "$DATA"
build_holos
emit_provenance "$RESULTS" "holos vs giotto-ph run"

cloud="$DATA/giotto_cloud_${N}.csv"
lower="$DATA/giotto_cloud_${N}.lower"
python3 "$HERE/gen_cloud.py" "$N" "$COORD_DIM" "$SEED" >"$cloud"
cloud_to_lower "$cloud" >"$lower"

GPH_VERSION="$(python3 -c 'import gph; print(getattr(gph, "__version__", "unknown"))' 2>/dev/null || echo unknown)"

{
    echo "giotto-ph version: $GPH_VERSION"
    echo "cloud: gen_cloud.py $N $COORD_DIM $SEED"
    echo "maxdim: $MAXDIM  threshold: $THRESHOLD  threads: ${THREAD_LIST[*]}"
    echo "holos reads the lower-distance file; giotto-ph reads the same cloud (euclidean)"
    echo
} >>"$RESULTS"

{
    echo "<!-- Generated by benchmarks/giotto_compare.sh. Do not edit; rerun the script. -->"
    echo
    echo "- N: $N  coord dim: $COORD_DIM  seed: $SEED  maxdim: $MAXDIM  threshold: $THRESHOLD"
    echo "- giotto-ph: $GPH_VERSION"
    echo
    echo "| threads | holos wall (s) | giotto-ph wall (s) | diagrams match |"
    echo "|--:|--:|--:|:--|"
} >>"$RESULTS_MD"

# giotto-ph runner: reduce the cloud at n_threads, write a ripser-format
# diagram to $2, then print its own wall time as "wall_s=<s>".
run_giotto() {
    python3 - "$cloud" "$1" "$2" "$MAXDIM" "$THRESHOLD" <<'EOF'
import sys
import time

import numpy as np
from gph import ripser_parallel

cloud, n_threads, out, maxdim, thresh = (
    sys.argv[1], int(sys.argv[2]), sys.argv[3], int(sys.argv[4]), float(sys.argv[5]),
)
pts = np.loadtxt(cloud, delimiter=",")
if pts.ndim == 1:
    pts = pts.reshape(1, -1)

start = time.monotonic()
res = ripser_parallel(pts, maxdim=maxdim, thresh=thresh, n_threads=n_threads)
wall = time.monotonic() - start

with open(out, "w") as f:
    for dim, dgm in enumerate(res["dgms"]):
        f.write(f"persistence intervals in dim {dim}:\n")
        for birth, death in dgm:
            d = "" if death == float("inf") else repr(float(death))
            f.write(f" [{repr(float(birth))},{d})\n")

print(f"wall_s={wall:.3f}")
EOF
}

ANY_MISMATCH=0
for t in "${THREAD_LIST[@]}"; do
    holos_out="$DATA/giotto_holos_${N}_t${t}.out"
    giotto_out="$DATA/giotto_gph_${N}_t${t}.out"

    holos_stats="$(measure "$holos_out" "$HOLOS_BIN" "$lower" \
        --format lower-distance --dim "$MAXDIM" --threshold "$THRESHOLD" --threads "$t")"
    holos_wall="${holos_stats#wall_s=}"; holos_wall="${holos_wall%% *}"

    giotto_stats="$(run_giotto "$t" "$giotto_out")"
    giotto_wall="${giotto_stats#wall_s=}"

    match="$(compare_diagrams "$holos_out" "$giotto_out")"
    [[ "$match" != yes ]] && ANY_MISMATCH=1

    {
        echo "== threads=$t"
        echo "holos  $holos_stats"
        echo "giotto $giotto_stats"
        echo "DIAGRAMS_MATCH $match"
        echo
    } >>"$RESULTS"
    echo "| $t | $holos_wall | $giotto_wall | $match |" >>"$RESULTS_MD"
    echo "threads=$t holos=${holos_wall}s giotto=${giotto_wall}s match=$match" >&2
done

echo "Results written to $RESULTS and $RESULTS_MD." >&2

if [[ "$ANY_MISMATCH" -ne 0 ]]; then
    echo "FAILURE: holos and giotto-ph diagrams disagree at some thread count; timings void." >&2
    exit 1
fi
