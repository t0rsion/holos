"""Generated raw and Markdown study records."""

from __future__ import annotations

import shlex
import statistics
from dataclasses import dataclass
from pathlib import Path

from v10_checker import CheckerMeasurement, command_text


@dataclass(frozen=True)
class EntryResult:
    entry: dict
    command: list[str]
    fields: dict[str, str]
    binding: str
    checker: CheckerMeasurement


def decisions(results: list[EntryResult]) -> dict[str, str]:
    exact = all(int(item.fields["strict_acceptances"]) > 0 for item in results)
    accepted = all(
        float(item.fields["evaluate_speedup"]) >= 2.5
        and int(item.fields["break_even_steps"]) <= item.entry["steps"]
        for item in results
    )
    omit_median = statistics.median(
        float(item.fields["omit_speedup"]) for item in results
    )
    exact_median = statistics.median(
        float(item.fields["exact_speedup"]) for item in results
    )
    return {
        "strict_acceptance": "pass" if exact else "fail",
        "accepted_evaluation": "pass" if accepted else "fail",
        "omit_median": f"{omit_median:.6f}",
        "exact_median": f"{exact_median:.6f}",
    }


def write_raw(
    path: Path,
    metadata: list[str],
    results: list[EntryResult],
) -> None:
    lines = list(metadata)
    for result in results:
        lines.append(f"entry={result.entry['id']} binding_sha256={result.binding}")
        lines.append(f"command={shlex.join(result.command)}")
        lines.append(
            f"independent_program_command={command_text(result.checker.program_command)}"
        )
        lines.append(
            f"independent_trace_command={command_text(result.checker.trace_command)}"
        )
        lines.append(
            "record="
            + " ".join(
                f"{key}={value}"
                for key, value in (result.fields | result.checker.fields()).items()
            )
        )
    path.write_text("\n".join(lines) + "\n")


def write_markdown(
    path: Path,
    metadata: dict[str, str],
    outcome: dict[str, str],
    results: list[EntryResult],
) -> None:
    lines = [
        "<!-- Generated by benchmarks/v10_program_bench.py. Do not edit. -->",
        "",
        f"- Commit: `{metadata['commit']}`",
        f"- Corpus: `{metadata['corpus']}` version {metadata['corpus_version']}, SHA-256 `{metadata['corpus_sha256']}`",
        f"- Set: {metadata['set']}",
        f"- Repetitions: {metadata['repetitions']} timed samples per arm; evaluation and omitted-update pairs are counterbalanced, with exactness checks outside their clocks",
        f"- CPU affinity: `{metadata['affinity']}`",
        f"- CPU: {metadata['cpu']}",
        f"- Platform: `{metadata['platform']}`",
        f"- Cargo: `{metadata['cargo']}`",
        f"- Binary SHA-256: `{metadata['binary_sha256']}`",
        f"- Independent checker SHA-256: `{metadata['checker_binary_sha256']}`",
        f"- Source tree dirty outside generated records: {metadata['source_dirty']}",
        "- Diagram comparison: exact at every step before each timing is retained",
        "- Strictness rule: every entry has a program acceptance rejected by the complete-order atlas",
        f"- Strictness decision: {outcome['strict_acceptance']}",
        "- Accepted-evaluation rule: at least 2.5 times faster in every entry, with compilation recovered within the trajectory",
        f"- Accepted-evaluation decision: {outcome['accepted_evaluation']}",
        f"- Median update speedup without correspondence: {float(outcome['omit_median']):.2f}x",
        f"- Median update speedup with exact correspondence: {float(outcome['exact_median']):.2f}x",
        "",
        "| entry | atoms | vertices | field | steps | complete guards | reduced guards | strict | strict fraction | compile ms | evaluate ms | recompute ms | speedup | break-even | update omit ms | update exact ms | rich ms | program KiB | trace KiB | producer program check ms | producer trace check ms | independent program check ms | independent trace check ms | trace peak MiB |",
        "|:--|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
    ]
    for result in results:
        entry = result.entry
        item = result.fields
        checker = result.checker.fields()
        lines.append(
            f"| {entry['id']} | {item['atoms']} | {item['vertices']} | Z/{item['modulus']} | {item['steps']} | "
            f"{item['complete_guards']} | {item['guards']} | {item['strict_acceptances']} | "
            f"{float(item['strict_fraction']):.3f} | "
            f"{milliseconds(item, 'compile_ns'):.3f} | "
            f"{milliseconds(item, 'evaluate_ns'):.3f} | {milliseconds(item, 'diagram_ns'):.3f} | "
            f"{float(item['evaluate_speedup']):.2f}x | {item['break_even_steps']} | "
            f"{milliseconds(item, 'update_omit_ns'):.3f} | {milliseconds(item, 'update_exact_ns'):.3f} | "
            f"{milliseconds(item, 'rich_ns'):.3f} | {int(item['program_bytes']) / 1024:.1f} | "
            f"{int(item['trace_bytes']) / 1024:.1f} | {milliseconds(item, 'program_verify_ns'):.3f} | "
            f"{milliseconds(item, 'trace_verify_ns'):.3f} | "
            f"{milliseconds(checker, 'independent_program_check_ns'):.3f} | "
            f"{milliseconds(checker, 'independent_trace_check_ns'):.3f} | "
            f"{int(checker['independent_trace_max_rss_kib']) / 1024:.1f} |"
        )
    path.write_text("\n".join(lines) + "\n")


def milliseconds(fields: dict[str, str], key: str) -> float:
    return int(fields[key]) / 1e6
