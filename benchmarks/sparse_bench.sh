#!/usr/bin/env bash
# Sparse against dense on the same geometry. Build a k-nearest-neighbour graph
# from a seeded cloud, then reduce it two ways: holos sparse on the kNN
# triplets, and holos dense on the densified matrix (absent pairs = +inf,
# threshold +inf). Reports wall time and peak RSS for each. Asserts the two
# diagrams are identical, because an absent edge and a +inf edge describe the
# same filtration.
#
# Results: benchmarks/results_sparse.txt (log) and .md (table), gitignored.
#
# CARGO may carry a toolchain: CARGO="cargo +1.92" ./sparse_bench.sh
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: sparse_bench.sh [-h]

Build a kNN sparse graph from a seeded cloud and reduce it via holos sparse
(triplets) vs holos dense (densified with +inf for absent pairs). Reports time
and peak RSS for each and asserts the diagrams are identical.

Environment:
  CARGO        cargo invocation (may carry a toolchain), default "cargo"
  N            cloud size (points), default 300
  COORD_DIM    coordinate dimension, default 3
  SEED         cloud seed, default 42
  K            neighbours per point, default 15
  MAXDIM       max homology dimension, default 2
  THREADS      reducer thread count, default 1
  ALLOW_DIRTY  set to 1 to benchmark a dirty worktree (recorded as -DIRTY)
EOF
}

[[ "${1:-}" == "-h" || "${1:-}" == "--help" ]] && { usage; exit 0; }

source "$(dirname "$0")/_common.sh"
require_proc

N="${N:-300}"
COORD_DIM="${COORD_DIM:-3}"
SEED="${SEED:-42}"
K="${K:-15}"
MAXDIM="${MAXDIM:-2}"
THREADS="${THREADS:-1}"

RESULTS="$HERE/results_sparse.txt"
RESULTS_MD="$HERE/results_sparse.md"

mkdir -p "$DATA"
build_holos
emit_provenance "$RESULTS" "holos sparse-vs-dense run"

cloud="$DATA/sparse_cloud_${N}.csv"
sparse_file="$DATA/sparse_${N}_k${K}.sparse"
lower="$DATA/sparse_${N}_k${K}.lower"
python3 "$HERE/gen_cloud.py" "$N" "$COORD_DIM" "$SEED" >"$cloud"

# kNN graph -> sparse "i j d" triplets and the densified condensed lower
# triangle (absent pairs +inf), from one distance computation. An undirected
# pair is kept if either endpoint ranks the other in its k nearest.
EDGE_COUNT="$(python3 - "$cloud" "$K" "$sparse_file" "$lower" <<'EOF'
import math
import sys

cloud, k, sparse_path, lower_path = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]

pts = []
with open(cloud) as f:
    for line in f:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        pts.append([float(t) for t in line.replace(",", " ").split()])

n = len(pts)
dmat = [[0.0] * n for _ in range(n)]
for i in range(n):
    for j in range(i + 1, n):
        d = math.dist(pts[i], pts[j])
        dmat[i][j] = dmat[j][i] = d

keep = [[False] * n for _ in range(n)]
kk = min(k, n - 1)
for i in range(n):
    order = sorted((j for j in range(n) if j != i), key=lambda j: dmat[i][j])
    for j in order[:kk]:
        keep[i][j] = keep[j][i] = True

edges = 0
with open(sparse_path, "w") as sp:
    for i in range(1, n):
        for j in range(i):
            if keep[i][j]:
                sp.write(f"{i} {j} {repr(dmat[i][j])}\n")
                edges += 1

inf = float("inf")
with open(lower_path, "w") as lo:
    for i in range(1, n):
        row = (repr(dmat[i][j]) if keep[i][j] else "inf" for j in range(i))
        lo.write(" ".join(row) + "\n")

print(edges)
EOF
)"

sparse_out="$DATA/sparse_${N}_sparse.out"
dense_out="$DATA/sparse_${N}_dense.out"

sparse_cmd=("$HOLOS_BIN" "$sparse_file" --format sparse --dim "$MAXDIM" --threads "$THREADS")
# Densified dense run: pass an explicit +inf threshold so the dense side does
# not fall back to its enclosing-radius default. It then stays equivalent to
# the no-threshold sparse default.
dense_cmd=("$HOLOS_BIN" "$lower" --format lower-distance --dim "$MAXDIM" --threshold inf --threads "$THREADS")

sparse_stats="$(measure "$sparse_out" "${sparse_cmd[@]}")"
dense_stats="$(measure "$dense_out" "${dense_cmd[@]}")"

sparse_wall="${sparse_stats#wall_s=}"; sparse_wall="${sparse_wall%% *}"
sparse_rss="${sparse_stats##*max_rss_kb=}"
dense_wall="${dense_stats#wall_s=}"; dense_wall="${dense_wall%% *}"
dense_rss="${dense_stats##*max_rss_kb=}"

match="$(compare_diagrams "$sparse_out" "$dense_out")"

{
    echo "cloud: gen_cloud.py $N $COORD_DIM $SEED"
    echo "knn: k=$K  edges=$EDGE_COUNT  (dense pairs = $((N * (N - 1) / 2)))"
    echo "maxdim: $MAXDIM  threads: $THREADS"
    echo "sparse cmd: ${sparse_cmd[*]}"
    echo "sparse  $sparse_stats"
    echo "dense cmd:  ${dense_cmd[*]}"
    echo "dense   $dense_stats"
    echo "DIAGRAMS_MATCH $match"
    echo
} >>"$RESULTS"

{
    echo "<!-- Generated by benchmarks/sparse_bench.sh. Do not edit; rerun the script. -->"
    echo
    echo "- N: $N  coord dim: $COORD_DIM  seed: $SEED  k: $K  maxdim: $MAXDIM  threads: $THREADS"
    echo "- kNN edges: $EDGE_COUNT of $((N * (N - 1) / 2)) dense pairs"
    echo
    echo "| variant | wall (s) | peak RSS (MB) |"
    echo "|:--|--:|--:|"
    echo "| holos sparse | $sparse_wall | $(kb_to_mb "$sparse_rss") |"
    echo "| holos dense (densified) | $dense_wall | $(kb_to_mb "$dense_rss") |"
    echo
    echo "diagrams match: $match"
} >"$RESULTS_MD"

echo "sparse wall=${sparse_wall}s rss=$(kb_to_mb "$sparse_rss")MB  dense wall=${dense_wall}s rss=$(kb_to_mb "$dense_rss")MB  match=$match" >&2
echo "Results written to $RESULTS and $RESULTS_MD." >&2

if [[ "$match" != yes ]]; then
    echo "FAILURE: sparse and densified-dense diagrams disagree; timings void." >&2
    exit 1
fi
