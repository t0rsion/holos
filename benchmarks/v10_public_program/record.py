"""Generated records and fixed outcome classifications."""

from __future__ import annotations

from pathlib import Path

from v10_checker import CheckerMeasurement, command_text


def classify(fields: dict[str, str]) -> dict[str, str]:
    transitions = int(fields["transitions"])
    reused = int(fields["reused_steps"])
    reuse_fraction = reused / transitions
    if reuse_fraction >= 0.5:
        reuse = "frequent"
    elif reuse_fraction >= 0.1:
        reuse = "intermittent"
    else:
        reuse = "rare"
    speedup = float(fields["update_speedup"])
    runtime = "faster" if speedup >= 1.0 else "slower"
    strict = "observed" if int(fields["strict_acceptances"]) > 0 else "not-observed"
    return {"reuse": reuse, "runtime": runtime, "strictness": strict}


def write_raw(
    path: Path,
    metadata: dict[str, str],
    outcome: dict[str, str],
    fields: dict[str, str],
    command: list[str],
    checker: CheckerMeasurement,
) -> None:
    import shlex

    lines = [f"{key}={value}" for key, value in metadata.items()]
    lines.extend(f"{key}={value}" for key, value in outcome.items())
    lines.append(f"command={shlex.join(command)}")
    lines.append(f"independent_program_command={command_text(checker.program_command)}")
    lines.append(f"independent_trace_command={command_text(checker.trace_command)}")
    lines.append(
        "record="
        + " ".join(
            f"{key}={value}" for key, value in (fields | checker.fields()).items()
        )
    )
    path.write_text("\n".join(lines) + "\n")


def write_markdown(
    path: Path,
    metadata: dict[str, str],
    outcome: dict[str, str],
    fields: dict[str, str],
    checker: CheckerMeasurement,
) -> None:
    checker_fields = checker.fields()
    lines = [
        "<!-- Generated by benchmarks/v10_public_program_bench.py. Do not edit. -->",
        "",
        f"- Commit: `{metadata['commit']}`",
        f"- Dataset: {fields['dataset']}",
        f"- Source URL: `{metadata['source_url']}`",
        f"- Source SHA-256: `{metadata['source_sha256']}`",
        f"- Prepared trajectory SHA-256: `{metadata['trajectory_sha256']}`",
        f"- Corpus: `{metadata['corpus']}` version {metadata['corpus_version']}, SHA-256 `{metadata['corpus_sha256']}`",
        f"- Repetitions: {metadata['repetitions']} timed samples per arm; update and fresh-recompute clocks are counterbalanced, with exactness checks outside their clocks",
        f"- CPU affinity: `{metadata['affinity']}`",
        f"- CPU: {metadata['cpu']}",
        f"- Cargo: `{metadata['cargo']}`",
        f"- Binary SHA-256: `{metadata['binary_sha256']}`",
        f"- Independent checker SHA-256: `{metadata['checker_binary_sha256']}`",
        f"- Source tree dirty outside generated data and records: {metadata['source_dirty']}",
        "- Diagram comparison: exact at every snapshot before each timing is retained",
        f"- Guard reuse classification: {outcome['reuse']}",
        f"- Runtime classification: program updates were {outcome['runtime']} than fresh diagram computation",
        f"- Strict acceptance: {outcome['strictness']}",
        "",
        "| vertices | edges | snapshots | field | atoms | complete guards | reduced guards | accepted | accepted fraction | strict | strict fraction | reused | repaired | recompiled | compile ms | update ms | recompute ms | speedup | program KiB | trace KiB | producer program check ms | producer trace check ms | independent program check ms | independent trace check ms | trace peak MiB |",
        "|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
        "| "
        + " | ".join(
            [
                fields["vertices"],
                fields["edges"],
                fields["snapshots"],
                f"Z/{fields['modulus']}",
                fields["initial_atoms"],
                fields["initial_complete_guards"],
                fields["initial_guards"],
                fields["accepted_steps"],
                f"{float(fields['accepted_fraction']):.3f}",
                fields["strict_acceptances"],
                f"{float(fields['strict_fraction']):.3f}",
                fields["reused_steps"],
                fields["repaired_steps"],
                fields["recompiled_steps"],
                milliseconds(fields, "compile_ns"),
                milliseconds(fields, "update_ns"),
                milliseconds(fields, "diagram_ns"),
                f"{float(fields['update_speedup']):.2f}x",
                f"{int(fields['program_bytes']) / 1024:.1f}",
                f"{int(fields['trace_bytes']) / 1024:.1f}",
                milliseconds(fields, "program_verify_ns"),
                milliseconds(fields, "trace_verify_ns"),
                milliseconds(checker_fields, "independent_program_check_ns"),
                milliseconds(checker_fields, "independent_trace_check_ns"),
                f"{int(checker_fields['independent_trace_max_rss_kib']) / 1024:.1f}",
            ]
        )
        + " |",
    ]
    path.write_text("\n".join(lines) + "\n")


def milliseconds(fields: dict[str, str], key: str) -> str:
    return f"{int(fields[key]) / 1e6:.3f}"
