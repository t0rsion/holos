#!/usr/bin/env python3
"""Generate the deterministic version 0.10 application record.

Usage: v10_application.py

Environment:
  CARGO  Cargo command, including an optional toolchain. The default is
         ``cargo``.
"""

import hashlib
import os
from pathlib import Path
import platform
import subprocess


ROOT = Path(__file__).resolve().parent.parent
HERE = ROOT / "benchmarks"


def text(command):
    return subprocess.run(
        [str(item) for item in command],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=True,
    ).stdout.strip()


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as source:
        for block in iter(lambda: source.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def main():
    cargo = os.environ.get("CARGO", "cargo").split()
    subprocess.run(
        [
            *cargo,
            "build",
            "--release",
            "-p",
            "holos-tda",
            "--example",
            "v10_application",
            "--locked",
        ],
        cwd=ROOT,
        check=True,
    )
    binary = ROOT / "target/release/examples/v10_application"
    record = text(["taskset", "-c", "0-3,12-15", binary])
    if not record.startswith("format=holos-program-application-v1 "):
        raise SystemExit(f"unexpected application record: {record}")
    commit = text(["git", "rev-parse", "HEAD"])
    metadata = [
        f"commit={commit}",
        f"platform={platform.platform()}",
        f"cargo={text([*cargo, '--version'])}",
        f"binary_sha256={sha256(binary)}",
        f"record={record}",
    ]
    (HERE / "results_v10_application.txt").write_text(
        "\n".join(metadata) + "\n")
    fields = dict(item.split("=", 1) for item in record.split())
    markdown = [
        "<!-- Generated by benchmarks/v10_application.py. Do not edit. -->",
        "",
        f"- Commit: `{commit}`",
        f"- Platform: `{platform.platform()}`",
        f"- Cargo: `{text([*cargo, '--version'])}`",
        f"- Binary SHA-256: `{sha256(binary)}`",
        "- All program, trace, and intervention artifacts were independently checked before this record was emitted.",
        "",
        "| field | value |",
        "|:--|--:|",
    ]
    for key, value in fields.items():
        markdown.append(f"| {key.replace('_', ' ')} | {value} |")
    (HERE / "results_v10_application.md").write_text(
        "\n".join(markdown) + "\n")
    print("wrote benchmarks/results_v10_application.txt and benchmarks/results_v10_application.md")


if __name__ == "__main__":
    main()
