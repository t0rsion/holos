"""Collect provenance and render the bipersistence study record."""

from __future__ import annotations

import hashlib
import os
import shlex
import subprocess
from collections.abc import Iterable, Mapping, Sequence
from datetime import datetime, timezone
from pathlib import Path

from .execute import StudyResult, maximum, median_upper


def collect_environment(
    root: Path,
    binaries: Mapping[str, Path],
    affinity: str,
    cargo_command: str,
) -> dict[str, object]:
    """Collect build identity, machine details, and worktree state."""

    status = subprocess.run(
        ["git", "-C", str(root), "status", "--porcelain", "--untracked-files=all"],
        text=True,
        capture_output=True,
        check=True,
    ).stdout
    commit = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "HEAD"],
        text=True,
        capture_output=True,
        check=True,
    ).stdout.strip()
    cargo_parts = shlex.split(cargo_command)
    cargo_version = _command_text([*cargo_parts, "--version"])
    rustc_parts = list(cargo_parts)
    if rustc_parts and rustc_parts[0].endswith("cargo"):
        rustc_parts[0] = rustc_parts[0][:-5] + "rustc"
    rustc_version = _command_text([*rustc_parts, "-V"])
    binary_data = {}
    for name, path in binaries.items():
        binary_data[name] = {
            "path": _relative_path(root, path),
            "sha256": _sha256(path),
        }
    holos_version = _command_text([str(binaries["holos"]), "--version"])
    actual_affinity = _format_cpu_set(os.sched_getaffinity(0))
    return {
        "recorded_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "commit": commit,
        "tree_state": "dirty" if status else "clean",
        "cargo": cargo_version,
        "rustc": rustc_version,
        "cpu": _cpu_model(),
        "requested_affinity": affinity,
        "effective_affinity": actual_affinity,
        "binaries": binary_data,
        "holos_version": holos_version,
    }


def render_record(environment: Mapping[str, object], study: StudyResult) -> str:
    """Render a concise Markdown record from observed values."""

    lines = [
        "# Synthetic bipersistence study",
        "",
        "This record is generated by `benchmarks/v09_bipersistence.sh`.",
        "",
        "## Environment",
        "",
        f"- recorded: `{environment['recorded_at']}`",
        f"- commit: `{environment['commit']}`",
        f"- worktree: `{environment['tree_state']}`",
        f"- cargo: `{environment['cargo']}`",
        f"- rustc: `{environment['rustc']}`",
        f"- CPU: {environment['cpu']}",
        f"- requested affinity: `{environment['requested_affinity']}`",
        f"- effective affinity: `{environment['effective_affinity']}`",
        f"- holos version: `{environment['holos_version']}`",
        "",
        "| binary | path | SHA-256 |",
        "|:--|:--|:--|",
    ]
    binaries = environment["binaries"]
    assert isinstance(binaries, Mapping)
    for name, details in binaries.items():
        assert isinstance(details, Mapping)
        lines.append(f"| `{name}` | `{details['path']}` | `{details['sha256']}` |")

    lines.extend(
        [
            "",
            "## Frozen structural evidence",
            "",
            "The graph edges and grid axes are explicit in `data.py`.",
            "",
            "| case | vertices | edges | axes | nodes | cover maps | rectangles | regions | atlas kinds | circular families |",
            "|:--|--:|--:|:--|--:|--:|--:|--:|:--|--:|",
        ]
    )
    for result in study.cases:
        case = result.case
        axes = f"r={_format_values(case.scales)}; k={_format_values(case.minimum_degrees)}"
        kinds = _format_counts(result.atlas_kinds)
        lines.append(
            f"| `{case.name}` | {case.vertex_count} | {len(case.edges)} | `{axes}` | "
            f"{result.producer['nodes']} | {result.producer['covers']} | "
            f"{result.producer['rectangles']} | {result.producer['regions']} | "
            f"{kinds} | {result.producer['circular']} |"
        )

    lines.extend(
        [
            "",
            "## Connected-region claims",
            "",
            "Each region is checked on the induced comparable subposet.",
            "",
            "| case | grades | rank |",
            "|:--|:--|--:|",
        ]
    )
    for result in study.cases:
        for region in result.report.get("regions", []):
            grades = " ".join(
                f"({grade[0]},{grade[1]})" for grade in region["grades"]
            )
            lines.append(f"| `{result.case.name}` | `{grades}` | {region['rank']} |")

    lines.extend(
        [
            "",
            "## Measured runs",
            "",
            "Each cell reports the upper median and maximum of the completed runs.",
            "",
            "| case | repetitions | producer median ns | producer maximum ns | checker median ns | checker maximum ns | artifact SHA-256 | report SHA-256 |",
            "|:--|--:|--:|--:|--:|--:|:--|:--|",
        ]
    )
    for result in study.cases:
        lines.append(
            f"| `{result.case.name}` | {len(result.producer_times_ns)} | "
            f"{median_upper(result.producer_times_ns)} | {maximum(result.producer_times_ns)} | "
            f"{median_upper(result.checker_times_ns)} | {maximum(result.checker_times_ns)} | "
            f"`{result.artifact_sha256}` | `{result.report_sha256}` |"
        )
    lines.extend(
        [
            "",
            "| Rust API study | repetitions | wall median ns | wall maximum ns | work |",
            "|:--|--:|--:|--:|:--|",
            (
                f"| `research-bench` | {len(study.research_bench_times_ns)} | "
                f"{median_upper(study.research_bench_times_ns)} | "
                f"{maximum(study.research_bench_times_ns)} | "
                f"`{study.research_bench_work}` |"
            ),
        ]
    )

    lines.extend(
        [
            "",
            "## Integrity gates",
            "",
            "| gate | result |",
            "|:--|:--|",
            "| independent `holos-check` on every artifact | `pass` |",
            f"| modulus-two circular-family rejection | `{_pass_fail(study.circular_modulus_gate)}` |",
        ]
    )
    for result in study.cases:
        lines.append(
            f"| corruption rejection for `{result.case.name}` | "
            f"`{_pass_fail(result.corruption_rejected)}` |"
        )
    lines.extend(
        [
            "",
            "The record is descriptive. It does not publish a performance claim.",
            "",
        ]
    )
    return "\n".join(lines)


def write_record(path: Path, environment: Mapping[str, object], study: StudyResult) -> None:
    """Write a generated Markdown record."""

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_record(environment, study), encoding="utf-8")


def _command_text(command: Sequence[str]) -> str:
    completed = subprocess.run(command, text=True, capture_output=True, check=True)
    return " ".join(completed.stdout.strip().splitlines())


def _relative_path(root: Path, path: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.name


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 16), b""):
            digest.update(block)
    return digest.hexdigest()


def _cpu_model() -> str:
    try:
        for line in Path("/proc/cpuinfo").read_text(encoding="utf-8").splitlines():
            if line.lower().startswith("model name"):
                return line.split(":", 1)[1].strip()
    except (OSError, IndexError):
        pass
    return "unknown"


def _format_cpu_set(cpus: Iterable[int]) -> str:
    values = sorted(set(cpus))
    if not values:
        return "empty"
    ranges = []
    start = previous = values[0]
    for value in values[1:]:
        if value == previous + 1:
            previous = value
            continue
        ranges.append(_format_range(start, previous))
        start = previous = value
    ranges.append(_format_range(start, previous))
    return ",".join(ranges)


def _format_range(start: int, end: int) -> str:
    return str(start) if start == end else f"{start}-{end}"


def _format_counts(counts: Mapping[str, int]) -> str:
    if not counts:
        return "none"
    return ", ".join(f"{key}={value}" for key, value in sorted(counts.items()))


def _format_values(values: Iterable[object]) -> str:
    return "[" + ",".join(str(value) for value in values) + "]"


def _pass_fail(value: bool) -> str:
    return "pass" if value else "fail"
