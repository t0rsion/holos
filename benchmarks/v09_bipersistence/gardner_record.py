"""Render the checked Gardner degree-Rips study record."""

from __future__ import annotations

import json
import platform
from collections.abc import Mapping
from importlib import metadata
from pathlib import Path

from .gardner_data import EXPECTED_NODE_RANKS, MINIMUM_DEGREES, REGION, SCALES
from .gardner_execute import GardnerResult, timing_summary


def write_record(
    path: Path,
    environment: Mapping[str, object],
    input_metadata: Mapping[str, object],
    result: GardnerResult,
) -> None:
    """Write the generated Markdown record and a compact JSON evidence file."""

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_record(environment, input_metadata, result), encoding="utf-8"
    )
    evidence_path = path.with_suffix(".json")
    evidence_path.write_text(
        json.dumps(
            compact_evidence(environment, input_metadata, result),
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )


def compact_evidence(
    environment: Mapping[str, object],
    input_metadata: Mapping[str, object],
    result: GardnerResult,
) -> dict[str, object]:
    """Return the values used by tables and paper figures."""

    atlases = result.report["class_atlases"]
    return {
        "environment": dict(environment),
        "input": dict(input_metadata),
        "grid": {
            "scales": SCALES,
            "minimum_degrees": MINIMUM_DEGREES,
            "node_ranks": EXPECTED_NODE_RANKS,
        },
        "rectangle_rank": result.report["rectangles"][0]["rank"],
        "region": {"grades": REGION, "rank": result.report["regions"][0]["rank"]},
        "extension_kinds": [
            {
                "grade": item["grade"],
                "kind": item["kind"],
                "ambiguity_rank": item["ambiguity_rank"],
            }
            for item in atlases[0]["extensions"]
        ],
        "atlas_region_count": atlases[0]["region_count"],
        "selected_classes": len(atlases),
        "circular_families": len(result.report["circular_families"]),
        "coordinate_lengths": [
            [
                None if item["phase"] is None else len(item["phase"])
                for item in family["entries"]
            ]
            for family in result.report["circular_families"]
        ],
        "artifact_bytes": result.artifact_bytes,
        "artifact_sha256": result.artifact_sha256,
        "report_sha256": result.report_sha256,
        "corruption_rejected": result.corruption_rejected,
        "repetitions": len(result.producer_times_ns),
        "timings": timing_summary(result),
    }


def render_record(
    environment: Mapping[str, object],
    input_metadata: Mapping[str, object],
    result: GardnerResult,
) -> str:
    """Render the application record from checked observations."""

    timings = timing_summary(result)
    lines = [
        "# Gardner degree-Rips class-extension study",
        "",
        "This record is generated by `benchmarks/v09_bipersistence_neuroscience.sh`.",
        "",
        "## Scope",
        "",
        "The input is rat R, module 2, day 1, open field. The preparation follows the authors' tagged preprocessing code. It uses 400 landmarks, not the 1,200 landmarks in the source paper. This study checks a finite degree-Rips grid. It does not reproduce the population analysis.",
        "",
        "## Provenance",
        "",
        f"- recorded: `{environment['recorded_at']}`",
        f"- commit: `{environment['commit']}`",
        f"- worktree: `{environment['tree_state']}`",
        f"- data DOI: `{input_metadata['data_doi']}`",
        f"- archive MD5: `{input_metadata['archive_md5']}`",
        f"- analysis source commit: `{input_metadata['source_commit']}`",
        f"- Python: `{platform.python_version()}`",
        f"- NumPy: `{metadata.version('numpy')}`",
        f"- SciPy: `{metadata.version('scipy')}`",
        f"- ripser.py: `{metadata.version('ripser')}`",
        f"- scikit-learn: `{metadata.version('scikit-learn')}`",
        f"- requested affinity: `{environment['requested_affinity']}`",
        f"- effective affinity: `{environment['effective_affinity']}`",
        "",
        f"The graph has {input_metadata['landmarks']} vertices and {input_metadata['edges']} edges. The source recording contributes {input_metadata['cells']} pure cells.",
        "",
        "## Finite module",
        "",
        f"Scales: `{list(SCALES)}`. Minimum degrees: `{list(MINIMUM_DEGREES)}`.",
        "",
        "| minimum degree / scale | 1 | 2 | 4.88695400387049 |",
        "|:--|--:|--:|--:|",
    ]
    for density_index, degree in enumerate(MINIMUM_DEGREES):
        ranks = [
            EXPECTED_NODE_RANKS[scale_index * len(MINIMUM_DEGREES) + density_index]
            for scale_index in range(len(SCALES))
        ]
        lines.append(f"| {degree} | {ranks[0]} | {ranks[1]} | {ranks[2]} |")
    grades = " ".join(f"({s},{d})" for s, d in REGION)
    lines.extend(
        [
            "",
            f"The connected region `{grades}` has generalized rank 2. The queried product rectangle also has rank 2. A product rectangle has a unique minimum and maximum, so this rectangle result equals its corner-map rank.",
            "",
            "## Selected classes",
            "",
            "Both longest ripser H1 cocycles select a class at grade `(0,1)`. They have the same extension classification.",
            "",
            "| grade | extension | ambiguity rank | circular coordinate |",
            "|:--|:--|--:|:--|",
        ]
    )
    for item in result.report["class_atlases"][0]["extensions"]:
        coordinate = "present" if item["kind"] == "unique" else "withheld"
        lines.append(
            f"| `{tuple(item['grade'])}` | {item['kind']} | "
            f"{item['ambiguity_rank']} | {coordinate} |"
        )
    lines.extend(
        [
            "",
            "The density relaxation from minimum degree 10 to 0 makes both extension fibers ambiguous at the first two scales. At the terminal scale, both selected classes have unique extensions. Holos emits coordinates only for unique fibers.",
            "",
            "## Checked execution",
            "",
            f"The producer upper median is {timings['producer_median_ns']} ns, and its maximum is {timings['producer_maximum_ns']} ns over {len(result.producer_times_ns)} runs.",
            f"The checker upper median is {timings['checker_median_ns']} ns, and its maximum is {timings['checker_maximum_ns']} ns over {len(result.checker_times_ns)} runs.",
            f"The artifact contains {result.artifact_bytes} bytes and has SHA-256 `{result.artifact_sha256}`.",
            f"The report has SHA-256 `{result.report_sha256}`.",
            "The independent checker accepted every repeated artifact. It rejected a one-byte payload corruption.",
            "",
        ]
    )
    return "\n".join(lines)
