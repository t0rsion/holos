"""Render generated records for the external maintained-update study."""

from __future__ import annotations

import shlex
from pathlib import Path


def write_raw(
    path: Path,
    metadata: dict[str, str],
    record: dict[str, str],
    comparison: str,
    command: list[str],
) -> None:
    lines = [f"{key}={value}" for key, value in metadata.items()]
    lines.append(f"command={shlex.join(command)}")
    lines.append(
        "record=" + " ".join(f"{key}={value}" for key, value in record.items())
    )
    lines.append("comparison=" + comparison)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_markdown(
    path: Path,
    metadata: dict[str, str],
    record: dict[str, str],
    comparison: str,
) -> None:
    lines = [
        "<!-- Generated by benchmarks/v10_external/run.py. Do not edit. -->",
        "",
        f"- Commit: `{metadata['commit']}`",
        f"- Trajectory: `{metadata['trajectory']}` SHA-256 `{metadata['trajectory_sha256']}`",
        f"- BATS update project: `{metadata['update_commit']}`",
        f"- BATS headers: `{metadata['bats_commit']}`",
        f"- BATS license: {metadata['license']}",
        f"- Repetitions: {record['reps']} timed samples per arm; exactness checks run outside the clocks, and arm order is fixed",
        f"- CPU affinity: `{metadata['affinity']}`",
        f"- Source tree dirty outside generated records: {metadata['source_dirty']}",
        f"- Holos comparison: `{comparison}`",
        "",
        (
            "The BATS warm arm copies the initial reduced complex, then calls "
            "`ReducedFilteredChainComplex::update_filtration_general` for each transition. "
            "The timed update excludes filtration and update-information construction. "
            "The full-update arm includes both operations. The fresh arm reduces every "
            "post-initial snapshot from its already constructed filtration."
        ),
        "",
        (
            "Finite zero-length bars are omitted from both outputs because Holos omits "
            "zero-persistence pairs."
        ),
        "",
        "| vertices | edges | snapshots | cells | triangles | field | compile ms | warm update ms | full update ms | fresh ms | warm speedup | full speedup | exact |",
        "|--:|--:|--:|--:|--:|:--|--:|--:|--:|--:|--:|--:|:--|",
        (
            f"| {record['vertices']} | {record['edges']} | {record['snapshots']} | "
            f"{record['cells']} | {record['triangles']} | Z/{record['modulus']} | "
            f"{milliseconds(record['compile_ns']):.3f} | "
            f"{milliseconds(record['update_ns']):.3f} | "
            f"{milliseconds(record['full_update_ns']):.3f} | "
            f"{milliseconds(record['fresh_ns']):.3f} | "
            f"{record['update_speedup']}x | {record['full_speedup']}x | "
            f"{record['exact']} |"
        ),
        "",
        (
            "The comparison measures exact H0 and H1 bar agreement on every snapshot. "
            "It does not certify that the external implementation follows Holos's "
            "result-sensitive guard policy."
        ),
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def milliseconds(value: str) -> float:
    return int(value) / 1e6
