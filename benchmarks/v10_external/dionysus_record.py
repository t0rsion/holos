def parse_record(output: str) -> dict[str, str]:
    """Parse the final Dionysus record line."""

    for line in reversed(output.splitlines()):
        if line.startswith("format=holos-dionysus-v1 "):
            return dict(item.split("=", 1) for item in line.split())
    raise ValueError("Dionysus did not print a v1 record")


def milliseconds(value: str) -> float:
    """Convert a nanosecond field to milliseconds for the table."""

    return int(value) / 1e6
