"""Render the generated Dionysus maintained-vineyard record."""

from __future__ import annotations

import shlex
from pathlib import Path


def write_raw(
    path: Path,
    metadata: dict[str, str],
    record: str,
    comparison: str,
    command: list[str],
) -> None:
    """Write provenance and the unmodified machine-readable record."""

    lines = [f"{key}={value}" for key, value in metadata.items()]
    lines.append(f"command={shlex.join(command)}")
    lines.append(f"record={record}")
    lines.append(f"comparison={comparison}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


